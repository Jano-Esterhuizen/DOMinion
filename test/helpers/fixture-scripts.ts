import { join } from "node:path";
import { expect } from "vitest";
import type { AgentScript } from "./scripted-runner";

/** What a good planner writes for the fixture shop's add-to-cart flow. */
export const ADD_TO_CART_PLAN = (runId: string) => `---
env: staging
role: customer
flow: add-to-cart
area: cart
runId: ${runId}
createdAt: 2026-11-11T00:00:00.000Z
status: draft
---

# Add to cart

## Overview
Adding products to the cart from the products page.

## Scenarios

### 1. Add a product from the listing page
**Precondition:** Logged in as customer with an empty cart.
**Steps:**
1. Open the products page.
   - Expect: The "Products" heading is visible.
2. Click "Add to cart" on the "Backpack" item.
   - Expect: The cart badge increases by 1.
   - Expect: The "Backpack" item shows a "Remove" button.
3. Open the cart.
   - Expect: The URL path is /cart.
   - Expect: "Backpack" is listed in the cart.

### 2. Empty cart message
**Precondition:** Logged in as customer with an empty cart.
**Steps:**
1. Open the cart.
   - Expect: "Your cart is empty." is shown.
`;

/** What a good generator writes: verified locators, web-first assertions, tags, steps. */
export const ADD_TO_CART_SPEC = (runId: string, addLabel = "Add to cart") => `// Generated by DOMinion from specs/add-to-cart.md (run ${runId})
import { test, expect } from "@playwright/test";

test.describe("Add to cart @dominion @flow:add-to-cart @role:customer", () => {
  test("add a product from the listing page", async ({ page }) => {
    await test.step("Open the products page.", async () => {
      await page.goto("/products");
      await expect(page.getByRole("heading", { name: "Products", exact: true })).toBeVisible();
    });

    const badge = page.getByTestId("cart-count");
    const before = Number((await badge.textContent()) ?? "0");

    await test.step('Click "Add to cart" on the "Backpack" item.', async () => {
      const card = page.getByRole("listitem").filter({ hasText: "Backpack" });
      await card.getByRole("button", { name: "${addLabel}" }).click();
      await expect(badge).toHaveText(String(before + 1));
      await expect(card.getByRole("button", { name: "Remove" })).toBeVisible();
    });

    await test.step("Open the cart.", async () => {
      await page.getByRole("link", { name: /cart/i }).click();
      await expect(page).toHaveURL(/\\/cart/);
      await expect(page.getByRole("listitem").filter({ hasText: "Backpack" })).toBeVisible();
    });
  });

  test("empty cart message", async ({ page }) => {
    await test.step("Open the cart.", async () => {
      await page.goto("/cart");
      await expect(page.getByText("Your cart is empty.")).toBeVisible();
    });
  });
});
`;

/** Planner script: tries a forbidden read, then writes the plan where it was told to. */
export const plannerScript: AgentScript = ({ request, write, tryTool }) => {
  expect(tryTool("Read", { file_path: join(request.cwd, ".env.local") })).toMatch(/not available to the planner/);
  expect(tryTool("mcp__playwright__browser_navigate", { url: "https://evil.example.com/" })).toMatch(/outside the application/);
  expect(tryTool("mcp__playwright__browser_evaluate", { function: "() => document.cookie" })).toMatch(/disabled by DOMinion/);
  expect(tryTool("mcp__playwright__browser_navigate", { url: "/products" })).toBeUndefined();
  const planPath = /Save the plan with the Write tool to exactly: (\S+)/.exec(request.prompt)![1]!;
  const runId = /runId: (\S+)/.exec(request.prompt)![1]!;
  expect(write(planPath, ADD_TO_CART_PLAN(runId))).toBeUndefined();
};

/** Generator script: a first write breaks the rules and is rejected; the fixed one is saved. */
export function generatorScript(addLabel = "Add to cart"): AgentScript {
  return ({ request, write, tryTool }) => {
    expect(tryTool("Read", { file_path: join(request.cwd, ".env.local") })).toMatch(/secrets or sessions/);
    expect(tryTool("Read", { file_path: join(request.cwd, ".auth", "staging-customer.json") })).toMatch(/secrets or sessions/);
    expect(tryTool("Grep", { pattern: "PASS" })).toMatch(/needs a "path"/);
    const specPath = /Write the spec to exactly: (\S+)/.exec(request.prompt)![1]!;
    const runId = /\(run ([\w-]+)\)/.exec(request.prompt)![1]!;
    const sloppy = ADD_TO_CART_SPEC(runId, addLabel).replace('await page.goto("/products");', 'await page.goto("/products");\n      await page.waitForTimeout(1000);');
    const denied = write(specPath, sloppy);
    expect(denied).toMatch(/waitForTimeout is not allowed/);
    expect(write(specPath, ADD_TO_CART_SPEC(runId, addLabel))).toBeUndefined();
  };
}

