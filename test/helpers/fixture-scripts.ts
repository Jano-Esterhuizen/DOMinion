/** Flows a good discovery agent proposes for the fixture shop. */
export const FIXTURE_FLOWS = (baseURL: string) => ({
  flows: [
    { id: "add-to-cart", name: "Add to cart", priority: "critical", startUrl: `${baseURL}/products`, pagesInvolved: [`${baseURL}/products`, `${baseURL}/cart`], description: "Add a product from the listing to the cart and see it in the cart.", destructive: false },
    { id: "checkout", name: "Checkout", priority: "critical", startUrl: `${baseURL}/cart`, pagesInvolved: [`${baseURL}/cart`, `${baseURL}/checkout`], description: "Check out the cart up to the order review.", destructive: true },
    { id: "login", name: "Log in", priority: "critical", startUrl: `${baseURL}/login`, pagesInvolved: [`${baseURL}/login`, `${baseURL}/account`], description: "Log in and reach the account page.", destructive: false },
    { id: "search", name: "Search products", priority: "high", startUrl: `${baseURL}/`, pagesInvolved: [`${baseURL}/search`], description: "Search the catalog by product name.", destructive: false },
  ],
});

/** Discovery agent: checks it got the sitemap and no tools, then returns the flows. */
export function discoveryScript(baseURL: string, options: { invalidFirst?: boolean } = {}): AgentScript {
  let calls = 0;
  return ({ request }) => {
    calls += 1;
    expect(request.policy.builtinTools).toEqual([]);
    expect(request.mcp).toBeUndefined();
    expect(request.outputSchema).toBeDefined();
    expect(request.prompt).toContain("/products/:id");
    if (options.invalidFirst && calls === 1) return { structured: { flows: [{ id: "x" }] } };
    if (options.invalidFirst) expect(request.prompt).toContain("previous reply was rejected");
    return { structured: FIXTURE_FLOWS(baseURL) };
  };
}

const PLANS: Record<string, (runId: string) => string> = { "add-to-cart": ADD_TO_CART_PLAN, search: SEARCH_PLAN };
const SPECS: Record<string, (runId: string) => string> = { "add-to-cart": (r) => ADD_TO_CART_SPEC(r), search: SEARCH_SPEC };

/** Planner that writes the plan matching the flow id in its prompt (crawl mode plans several flows). */
export const multiPlannerScript: AgentScript = ({ request, write }) => {
  const planPath = /Save the plan with the Write tool to exactly: (\S+)/.exec(request.prompt)![1]!;
  const runId = /runId: (\S+)/.exec(request.prompt)![1]!;
  const flow = /^flow: (\S+)$/m.exec(request.prompt)![1]!;
  const plan = PLANS[flow] ?? ((r: string) => ADD_TO_CART_PLAN(r).replace("flow: add-to-cart", `flow: ${flow}`));
  expect(write(planPath, plan(runId))).toBeUndefined();
};

/** Generator that writes the spec matching the flow (by the describe title it was told to use). */
export const multiGeneratorScript: AgentScript = ({ request, write }) => {
  const specPath = /Write the spec to exactly: (\S+)/.exec(request.prompt)![1]!;
  const runId = /\(run ([\w-]+)\)/.exec(request.prompt)![1]!;
  const flow = /@flow:([\w-]+)/.exec(request.prompt)![1]!;
  expect(write(specPath, SPECS[flow]!(runId))).toBeUndefined();
};
