import { describe, expect, it } from "vitest";
import { hasDominionHeader, lintErrors, lintGeneratedFile } from "../../src/core/playwright/lint";
import { Redactor } from "../../src/core/redact";
import { ADD_TO_CART_SPEC } from "../helpers/fixture-scripts";

const ctx = { kind: "spec" as const, flowSlug: "add-to-cart", role: "customer", testImport: 'import { test, expect } from "@playwright/test";' };
const rules = (content: string, extra: Partial<Parameters<typeof lintGeneratedFile>[1]> = {}) =>
  lintErrors(lintGeneratedFile(content, { ...ctx, ...extra })).map((i) => i.rule);

describe("lintGeneratedFile", () => {
  it("accepts the spec's expected output", () => {
    expect(lintGeneratedFile(ADD_TO_CART_SPEC("2026-11-11-a1b2"), ctx)).toEqual([]);
  });

  it.each([
    ["no-xpath", 'await page.locator("//button").click();'],
    ["no-xpath", 'await page.locator("xpath=//div").click();'],
    ["no-wait-for-timeout", "await page.waitForTimeout(500);"],
    ["no-sleep", "await new Promise((r) => setTimeout(r, 100));"],
    ["no-element-handles", 'const el = await page.$("button");'],
    ["no-dom-position-selectors", 'await page.locator("ul > li:nth-child(2)").click();'],
    ["no-generated-classes", 'await page.locator(".css-1x2y3z4").click();'],
    ["web-first-assertions", 'expect(await page.getByRole("heading").textContent()).toBe("x");'],
    ["no-only", 'test.only("x", async () => {});'],
    ["no-pause", "await page.pause();"],
    ["positional-locator-needs-comment", 'await page.getByRole("listitem").first().click();'],
  ])("flags %s", (rule, line) => {
    const content = ADD_TO_CART_SPEC("r").replace('await page.goto("/products");', `await page.goto("/products");\n      ${line}`);
    expect(rules(content)).toContain(rule);
  });

  it("allows positional locators that explain themselves", () => {
    const inline = ADD_TO_CART_SPEC("r").replace('await page.goto("/products");', 'await page.goto("/products");\n      await page.getByRole("listitem").first().click(); // the plan says "the first product"');
    const above = ADD_TO_CART_SPEC("r").replace('await page.goto("/products");', 'await page.goto("/products");\n      // first product in the list, as the plan says\n      await page.getByRole("listitem").first().click();');
    expect(rules(inline)).not.toContain("positional-locator-needs-comment");
    expect(rules(above)).not.toContain("positional-locator-needs-comment");
  });

  it("ignores rule violations inside comments", () => {
    const content = ADD_TO_CART_SPEC("r").replace('await page.goto("/products");', 'await page.goto("/products");\n      // never use page.waitForTimeout(500) here');
    expect(rules(content)).toEqual([]);
  });

  it("requires the header, import, tags, describe and assertions", () => {
    expect(rules(ADD_TO_CART_SPEC("r").replace(/^\/\/ Generated.*\n/, ""))).toContain("header-comment");
    expect(rules(ADD_TO_CART_SPEC("r").replace("@flow:add-to-cart ", ""))).toContain("tags");
    expect(rules(ADD_TO_CART_SPEC("r").replace("@role:customer", "@role:admin"))).toContain("tags");
    expect(rules(ADD_TO_CART_SPEC("r"), { testImport: 'import { test, expect } from "../fixtures";' })).toContain("test-import");
    const noAsserts = `// Generated by DOMinion from specs/x.md (run r)\nimport { test, expect } from "@playwright/test";\ntest.describe("X @dominion @flow:add-to-cart @role:customer", () => { test("t", async ({ page }) => { await page.goto("/"); }); });\n`;
    expect(rules(noAsserts)).toContain("assert-outcomes");
  });

  it("rejects hardcoded credentials", () => {
    const redactor = new Redactor([{ name: "FX_PASS", value: "fixture-pass-PLAIN-0000" }]);
    const content = ADD_TO_CART_SPEC("r").replace('await page.goto("/products");', 'await page.goto("/products");\n      await page.getByLabel("Password").fill("fixture-pass-PLAIN-0000");');
    const issues = lintGeneratedFile(content, { ...ctx, redactor });
    expect(issues.find((i) => i.rule === "no-secrets")?.message).toContain("FX_PASS");
  });

  it("forbids assertions in page objects but not other rules' false positives", () => {
    const po = `// Generated by DOMinion from specs/x.md (run r)\nexport class CartPage {\n  readonly checkout = this.page.getByRole("link", { name: "Checkout" });\n  constructor(private readonly page: any) {}\n  async verify() { await expect(this.checkout).toBeVisible(); }\n}\n`;
    expect(lintErrors(lintGeneratedFile(po, { kind: "page-object" })).map((i) => i.rule)).toEqual(["no-assertions-in-page-objects"]);
  });

  it("detects the ownership header", () => {
    expect(hasDominionHeader("\n// Generated by DOMinion from specs/a.md (run 2026-11-11-a1b2)\nx")).toBe(true);
    expect(hasDominionHeader("// Generated by DOMinion: refreshes the saved session")).toBe(true);
    expect(hasDominionHeader('import { test } from "@playwright/test";')).toBe(false);
  });
});
