import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { afterEach, beforeAll, describe, expect, it } from "vitest";
import { loadConfig } from "../../src/core/config/loader";
import { projectPaths } from "../../src/core/config/resolve";
import { runInit } from "../../src/core/init";
import { ensureSetupFile, managedEntries, patchPlaywrightConfig, sessionHeadersImport } from "../../src/core/playwright/patch";
import { nonInteractivePrompter } from "../../src/core/prompter";
import { applyUninstall, planUninstall } from "../../src/core/uninstall";
import { buildCli, runCli } from "../helpers/cli";
import { makePlaywrightProject, removeDir, writeFiles } from "../helpers/tmp";

// A create-playwright style config: one multi-line project, one single-line project, and the
// commented-out projects it ships with. Uninstall must restore it byte for byte.
const PLAYWRIGHT_CONFIG = `import { defineConfig, devices } from '@playwright/test';

export default defineConfig({
  testDir: './tests',
  fullyParallel: true,
  use: {
    trace: 'on-first-retry',
  },
  projects: [
    {
      name: 'chromium',
      use: { ...devices['Desktop Chrome'] },
    },
    { name: 'firefox', use: { ...devices['Desktop Firefox'] } },
    // { name: 'webkit', use: { ...devices['Desktop Safari'] } },
  ],
});
`;

const HANDWRITTEN_TEST = `import { test, expect } from '@playwright/test';

test('home page', async ({ page }) => {
  await page.goto('/');
  await expect(page).toHaveTitle(/Shop/);
});
`;

const GENERATED = (plan: string) => `// Generated by DOMinion from ${plan} (run 20261113-r1)
import { test, expect } from "@playwright/test";

test.describe("Cart @dominion @flow:cart @role:customer", () => {
  test("adds a product", async ({ page }) => {
    await page.goto("/");
    await expect(page.getByRole("heading")).toBeVisible();
  });
});
`;

const PLAN = `---
env: staging
role: customer
flow: cart
runId: 20261113-r1
createdAt: 2026-11-13T10:00:00Z
status: approved
---

# Cart
`;

const dirs: string[] = [];
afterEach(() => {
  while (dirs.length) removeDir(dirs.pop()!);
});

beforeAll(() => buildCli());

function project(prefix: string, files: Record<string, string>): string {
  const root = makePlaywrightProject(prefix, files);
  dirs.push(root);
  return root;
}

/** A new project after setup and one run: every kind of file and edit DOMinion makes. */
async function newProjectWithDominion(): Promise<{ root: string; originalConfig: string }> {
  const root = project("uninstall-new", { "playwright.config.ts": PLAYWRIGHT_CONFIG, "tests/example.spec.ts": HANDWRITTEN_TEST, ".gitignore": "node_modules/\n" });
  const originalConfig = readFileSync(join(root, "playwright.config.ts"), "utf8");
  await runInit({ root, baseURL: "http://localhost:3000", prompter: nonInteractivePrompter(), ignoreOverlap: true });
  const loaded = await loadConfig({ cwd: root });
  // What a run adds: the managed projects (with an api role, so the sessionHeaders import too) and the setup file.
  const entries = managedEntries(loaded, root);
  const withApiRole = [...entries, { ...entries[entries.length - 1]!, role: "api_user", sessionHeaders: true }];
  expect(patchPlaywrightConfig(join(root, "playwright.config.ts"), withApiRole).status).toBe("patched");
  ensureSetupFile(projectPaths(loaded).testDir);
  writeFiles(root, {
    "tests/agent/cart/cart.spec.ts": GENERATED("specs/cart.md"),
    "tests/agent/pages/cart.page.ts": GENERATED("specs/cart.md"),
    "specs/cart.md": PLAN,
    "specs/notes.md": "# Our own notes, not a DOMinion plan\n",
    ".auth/staging-customer.json": '{"cookies":[],"origins":[]}',
    ".auth/staging-customer.headers.json": "{}",
    ".dominion/runs/20261113-r1/events.jsonl": "{}\n",
    "dominion/prompts/planner.md": "custom planner prompt\n",
  });
  writeFileSync(join(root, ".env.local"), `${readFileSync(join(root, ".env.local"), "utf8")}MY_OWN_VAR=keep-me\n`);
  return { root, originalConfig };
}

describe("dominion uninstall", () => {
  it("removes everything DOMinion added to a new project and restores playwright.config.ts exactly", async () => {
    const { root, originalConfig } = await newProjectWithDominion();
    const config = readFileSync(join(root, "playwright.config.ts"), "utf8");
    expect(config).toContain("dominion:start");
    expect(config).toContain(sessionHeadersImport());
    expect(config.match(/testIgnore: "\*\*\/tests\/agent\/\*\*"/g)).toHaveLength(2);

    const plan = await planUninstall(root);
    expect(plan.warnings).toEqual([]);
    expect(plan.steps.find((s) => s.path === "playwright.config.ts")?.detail).toBe(
      'remove DOMinion\'s projects, the sessionHeaders import, testIgnore: "**/tests/agent/**" (2 projects)',
    );
    expect(applyUninstall(plan).failed).toEqual([]);

    expect(readFileSync(join(root, "playwright.config.ts"), "utf8")).toBe(originalConfig);
    for (const gone of ["dominion.config.ts", "dominion", "tests/agent", ".auth", ".dominion", "specs/cart.md"]) {
      expect(existsSync(join(root, gone)), gone).toBe(false);
    }
    // Hand-written files and folders stay; so does .gitignore, which keeps secrets out of git.
    expect(readFileSync(join(root, "tests/example.spec.ts"), "utf8")).toBe(HANDWRITTEN_TEST);
    expect(existsSync(join(root, "specs/notes.md"))).toBe(true);
    expect(readFileSync(join(root, ".gitignore"), "utf8")).toContain(".env.local");
    // .env.local keeps only what DOMinion did not add (in the file's own line endings: a Windows
    // checkout of the template has CRLF).
    expect(readFileSync(join(root, ".env.local"), "utf8").replace(/\r\n/g, "\n")).toBe("MY_OWN_VAR=keep-me\n");

    const again = await planUninstall(root);
    expect(again.steps).toEqual([]);
  });

  it("keeps generated tests and plans with --keep-tests", async () => {
    const { root } = await newProjectWithDominion();
    const plan = await planUninstall(root, { keepTests: true });
    expect(plan.steps.map((s) => s.path)).not.toContain("tests/agent/cart/cart.spec.ts");
    expect(plan.kept.join("\n")).toContain("2 generated test files in tests/agent/");
    applyUninstall(plan);
    expect(existsSync(join(root, "tests/agent/cart/cart.spec.ts"))).toBe(true);
    expect(existsSync(join(root, "specs/cart.md"))).toBe(true);
    expect(existsSync(join(root, "tests/agent/dominion.setup.ts"))).toBe(false);
    expect(existsSync(join(root, "dominion.config.ts"))).toBe(false);
  });

  it("leaves an existing suite's own files and filled-in credentials alone", async () => {
    const login = `import { test } from '@playwright/test';

test('log in', async ({ page }) => {
  await page.goto('/login');
  await page.getByLabel('Email').fill(process.env.E2E_USER ?? '');
  await page.getByLabel('Password').fill(process.env.E2E_PASS ?? '');
});
`;
    const root = project("uninstall-existing", { "tests/login.spec.ts": login });
    const originalConfig = readFileSync(join(root, "playwright.config.ts"), "utf8");
    const init = await runInit({ root, baseURL: "http://localhost:3000", prompter: nonInteractivePrompter() });
    expect(init.mode).toBe("existing");
    writeFiles(root, { "tests/generated/cart.spec.ts": GENERATED("specs/cart.md") });
    // The suite's own variable, filled in by a person, stays; DOMinion's empty placeholder goes.
    const envLocal = readFileSync(join(root, ".env.local"), "utf8");
    expect(envLocal).toMatch(/^E2E_USER=$/m);
    writeFileSync(join(root, ".env.local"), envLocal.replace(/^E2E_USER=$/m, "E2E_USER=someone@example.test"));

    const plan = await planUninstall(root);
    expect(applyUninstall(plan).failed).toEqual([]);
    expect(existsSync(join(root, "playwright.dominion.config.ts"))).toBe(false);
    expect(existsSync(join(root, "tests/generated"))).toBe(false);
    expect(readFileSync(join(root, "tests/login.spec.ts"), "utf8")).toBe(login);
    expect(readFileSync(join(root, "playwright.config.ts"), "utf8")).toBe(originalConfig);
    expect(readFileSync(join(root, ".env.local"), "utf8").replace(/\r\n/g, "\n")).toBe("E2E_USER=someone@example.test\n");
    expect(plan.kept.join("\n")).toContain("your suite's own credentials");
  });

  it("lists, asks, and removes from the command line", async () => {
    const { root } = await newProjectWithDominion();

    const dry = await runCli(["uninstall", "--dry-run"], { cwd: root });
    expect(dry.status).toBe(0);
    expect(dry.stdout).toContain("Would remove from");
    expect(dry.stdout).toContain("edit   playwright.config.ts");
    expect(dry.stdout).toContain("delete dominion.config.ts");
    expect(existsSync(join(root, "dominion.config.ts"))).toBe(true);

    // Without a terminal to ask in, it refuses instead of deleting.
    const unconfirmed = await runCli(["uninstall"], { cwd: root });
    expect(unconfirmed.status).not.toBe(0);
    expect(unconfirmed.stderr).toContain("--yes");
    expect(existsSync(join(root, "dominion.config.ts"))).toBe(true);

    const removed = await runCli(["uninstall", "--yes"], { cwd: root });
    expect(removed.status, removed.stderr).toBe(0);
    expect(removed.stdout).toContain("DOMinion's files are gone.");
    expect(existsSync(join(root, "dominion.config.ts"))).toBe(false);

    const nothing = await runCli(["uninstall", "--yes"], { cwd: root });
    expect(nothing.stdout).toContain("Nothing of DOMinion's is left");
  });
});
