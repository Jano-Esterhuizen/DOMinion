let fixture: FixtureApp;
let root: string;
let restoreEnv: () => void;
let handWritten: ReturnType<typeof snapshotTree>;

const userFiles = (snapshot: ReturnType<typeof snapshotTree>) =>
  Object.fromEntries(Object.entries(snapshot).filter(([path]) => path === "playwright.config.ts" || (path.startsWith("e2e/") && !path.startsWith("e2e/generated"))).map(([p, s]) => [p, s.hash]));

beforeAll(async () => {
  buildCli();
  fixture = await startFixtureApp();
  restoreEnv = setEnv({ BASE_URL: fixture.url, E2E_USER: FIXTURE_USERS.plain.email, E2E_PASS: FIXTURE_USERS.plain.password });
  root = makeTempDir("existing");
  cpSync(join(REPO_ROOT, "test", "fixture-existing-suite"), root, { recursive: true });
  writeFiles(root, { ".git/HEAD": "ref: refs/heads/main\n" });
  linkDominionPackage(root);
  handWritten = snapshotTree(root);
});

afterAll(async () => {
  restoreEnv?.();
  await fixture?.close();
  if (root) removeDir(root);
});

const CHECKOUT_PLAN = (runId: string) => `---
env: staging
role: user
flow: checkout
area: checkout
runId: ${runId}
createdAt: 2026-11-11T00:00:00.000Z
status: draft
---

# Checkout

## Overview
Checking out the cart up to the order review. Placing the order is irreversible and not allowed in staging.

## Scenarios

### 1. Reach the order review with shipping details
**Precondition:** Logged in with an empty cart.
**Steps:**
1. Add the backpack to the cart.
   - Expect: The cart badge shows 1.
2. Open the cart and start checkout.
   - Expect: The "Checkout" heading is visible.
3. Fill in shipping details and continue.
   - Expect: The URL path is /checkout/review and "Review your order" is visible.
   - Stop before clicking "Place order" (irreversible; not allowed in staging).
`;

const CHECKOUT_SPEC = (runId: string) => `// Generated by DOMinion from specs/checkout.md (run ${runId})
import { test, expect } from "../fixtures";

test.describe("Checkout @dominion @flow:checkout @role:user", () => {
  test("reach the order review with shipping details", async ({ productsPage, cartPage, page }) => {
    await test.step("Add the backpack to the cart.", async () => {
      await productsPage.goto();
      await productsPage.addToCart("Backpack");
      await expect(productsPage.cartCount).toHaveText("1");
    });

    await test.step("Open the cart and start checkout.", async () => {
      await cartPage.goto();
      await cartPage.checkoutLink.click();
      await expect(page.getByRole("heading", { name: "Checkout" })).toBeVisible();
    });

    await test.step("Fill in shipping details and continue.", async () => {
      await page.getByLabel("Full name").fill("Test Shopper");
      await page.getByLabel("Address").fill("1 Test Street");
      await page.getByLabel("City").fill("Testville");
      await page.getByLabel("Postal code").fill("0001");
      await page.getByRole("button", { name: "Continue to review" }).click();
      await expect(page).toHaveURL(/\\/checkout\\/review/);
      await expect(page.getByRole("heading", { name: "Review your order" })).toBeVisible();
    });
  });
});
`;

function planner(plan: (runId: string) => string): AgentScript {
  return ({ request, write }) => {
    const planPath = /Save the plan with the Write tool to exactly: (\S+)/.exec(request.prompt)![1]!;
    const runId = /runId: (\S+)/.exec(request.prompt)![1]!;
    expect(write(planPath, plan(runId))).toBeUndefined();
  };
}

describe("init in a repo with an existing Playwright suite", () => {
  it("detects the suite and writes a project profile, without a second login mechanism", async () => {
    const result = await runInit({
      root,
      yes: true,
      baseURL: fixture.url,
      prompter: nonInteractivePrompter(),
      analyzeConventions: async () => "- Tests get page objects from fixtures (productsPage, cartPage).\n- Steps are lower-case phrases.",
    });
    expect(result.mode).toBe("existing");
    expect(result.profile).toMatchObject({
      playwrightConfig: "playwright.config.ts",
      testDir: "e2e",
      outputDir: "e2e/generated",
      fileNaming: "{flow}.test.ts",
      language: "ts",
      moduleFormat: "esm",
      testImport: 'import { test, expect } from "../fixtures"',
      pageObjects: { dir: "e2e/pages", style: "class", reuse: true },
      auth: { strategy: "existing", setupProject: "setup", storageState: "playwright/.auth/user.json" },
      modifyExisting: false,
      runProject: "chromium",
    });
    expect(result.files.map((f) => f.path)).not.toContain("dominion/auth/login.ts");
    expect(existsSync(join(root, "dominion", "auth", "login.ts"))).toBe(false);
    expect(readFileSync(join(root, "playwright.dominion.config.ts"), "utf8")).toContain('import base from "./playwright.config";');
    const config = await loadConfig({ cwd: root });
    expect(config.config.project?.conventions).toContain("fixtures");
    expect(config.config.environments.staging!.roles.user).toEqual({ strategy: "existing" });
    // The suite's setup reads E2E_USER / E2E_PASS: DOMinion treats them as secrets (redacted,
    // hidden from agents) and lists them in .env.local; BASE_URL is a setting, not a secret.
    expect(config.config.secretEnv).toEqual(["E2E_PASS", "E2E_USER"]);
    expect(result.nextSteps[0]).toContain("E2E_PASS, E2E_USER");
    const envLocal = readFileSync(join(root, ".env.local"), "utf8");
    expect(envLocal).toMatch(/^E2E_USER=$/m);
    expect(envLocal).not.toContain("BASE_URL");
    expect(userFiles(snapshotTree(root))).toEqual(userFiles(handWritten));
  });

  it("is idempotent", async () => {
    const before = snapshotTree(root);
    const again = await runInit({ root, yes: true, baseURL: fixture.url, prompter: nonInteractivePrompter() });
    expect(again.files.every((f) => f.status === "skipped")).toBe(true);
    expect(snapshotTree(root)).toEqual(before);
  });

  it("reuses the project's own setup project for the session", async () => {
    const loaded = await loadConfig({ cwd: root });
    const first = await ensureSession({ loaded, envName: "staging", roleName: "user", prompter: nonInteractivePrompter() });
    expect(first.action).toBe("logged-in");
    expect(first.file).toBe(join(root, "playwright", ".auth", "user.json"));
    const second = await ensureSession({ loaded, envName: "staging", roleName: "user", prompter: nonInteractivePrompter() });
    expect(second.action).toBe("reused");
  });
});

describe("task mode in the existing suite", () => {
  it("skips a flow the existing tests already cover", async () => {
    const scripted = scriptedRunner({
      planner: ({ request, write }) => {
        expect(request.prompt).toMatch(/Existing tests already cover this flow:\n- e2e\/cart\.test\.ts > "adds a product to the cart"/);
        const planPath = /Save the plan with the Write tool to exactly: (\S+)/.exec(request.prompt)![1]!;
        expect(write(planPath, "# Add a product to the cart\n\n## Overview\nAlready covered by e2e/cart.test.ts.\n\n## Scenarios\n")).toBeUndefined();
      },
    });
    const run = await runTask(
      { loaded: await loadConfig({ cwd: root }), envName: "staging", roleName: "user", request: "add a product to the cart", autoApprove: true },
      { runner: scripted.runner, interaction: autoApproveInteraction, prompter: nonInteractivePrompter(), skipPreflight: true },
    );
    expect(run.status).toBe("done");
    expect(run.flows[0]).toMatchObject({ status: "skipped", coverage: { status: "covered" } });
    expect(scripted.calls.map((c) => c.agent)).toEqual(["planner"]);
    expect(readPlan(join(root, "specs", "add-product-to-cart.md")).frontmatter.status).toBe("covered");
  });

  it("generates tests that use the suite's fixtures, page objects, naming and auth, and proposes changes to hand-written files", async () => {
    const scripted = scriptedRunner({
      planner: planner(CHECKOUT_PLAN),
      generator: ({ request, write, edit }) => {
        expect(request.prompt).toContain("Write the spec to exactly: e2e/generated/checkout.test.ts");
        expect(request.prompt).toContain('Import (exactly): import { test, expect } from "../fixtures"');
        expect(request.prompt).toContain("Style exemplars");
        expect(request.prompt).toMatch(/ProductsPage \(e2e\/pages\/ProductsPage\.ts\): methods goto, product, addToCart/);
        expect(request.prompt).toContain("Tests get page objects from fixtures");
        // A change to a hand-written page object becomes a proposal, not an edit.
        expect(edit("e2e/pages/CartPage.ts", "  async goto() {", "  async startCheckout() {\n    await this.checkoutLink.click();\n  }\n\n  async goto() {")).toMatch(/NOT applied/);
        // Writing outside the output and page-object folders is refused.
        expect(write("e2e/checkout.test.ts", "x")).toMatch(/limited to/);
        const runId = /\(run ([\w-]+)\)/.exec(request.prompt)![1]!;
        expect(write("e2e/generated/checkout.test.ts", CHECKOUT_SPEC(runId))).toBeUndefined();
      },
    });
    const run = await runTask(
      { loaded: await loadConfig({ cwd: root }), envName: "staging", roleName: "user", request: "checkout", autoApprove: true },
      { runner: scripted.runner, interaction: autoApproveInteraction, prompter: nonInteractivePrompter(), skipPreflight: true },
    );
    expect(run.status, run.error?.message).toBe("done");
    const flow = run.flows[0]!;
    expect(flow.specFiles).toEqual(["e2e/generated/checkout.test.ts"]);
    expect(flow.results?.map((r) => [r.title.split(" > ").pop(), r.status])).toEqual([["reach the order review with shipping details", "passed"]]);
    expect(run.proposals).toHaveLength(1);
    expect(run.proposals![0]).toMatchObject({ path: "e2e/pages/CartPage.ts", status: "pending" });
    expect(userFiles(snapshotTree(root))).toEqual(userFiles(handWritten));

    const store = new RunStore({ runsDir: join(root, ".dominion", "runs") }, new Redactor());
    const handle = store.get(run.id);
    expect(readFileSync(handle.path("proposals", "p1.diff"), "utf8")).toContain("+  async startCheckout() {");
    applyProposal(handle, root, "p1");
    expect(readFileSync(join(root, "e2e", "pages", "CartPage.ts"), "utf8")).toContain("async startCheckout()");
    expect(() => applyProposal(handle, root, "p1")).toThrow(/already applied/);
  });
});

describe("doctor on an existing project", () => {
  it("reports the profile as matching, then warns when it drifts", async () => {
    const env = { ...process.env, ANTHROPIC_API_KEY: "sk-ant-placeholder" };
    const ok = await runDoctor({ cwd: root, validateSessions: false, env });
    expect(ok.checks.find((c) => c.id === "profile")).toMatchObject({ status: "ok" });
    renameSync(join(root, "e2e", "fixtures.ts"), join(root, "e2e", "test-fixtures.ts"));
    try {
      const drifted = await runDoctor({ cwd: root, validateSessions: false, env });
      expect(drifted.checks.some((c) => c.title === "Project profile" && c.status === "warn" && /fixture module/.test(c.detail ?? ""))).toBe(true);
    } finally {
      renameSync(join(root, "e2e", "test-fixtures.ts"), join(root, "e2e", "fixtures.ts"));
    }
    writeFileSync(join(root, "playwright.config.ts"), readFileSync(join(root, "playwright.config.ts"), "utf8").replace('name: "setup"', 'name: "auth"').replace('dependencies: ["setup"]', 'dependencies: ["auth"]'));
    const broken = await runDoctor({ cwd: root, validateSessions: false, env });
    expect(broken.checks.some((c) => c.status === "error" && /Setup project "setup" is not in/.test(c.detail ?? ""))).toBe(true);
  });
});
