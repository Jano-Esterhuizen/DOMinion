import { useEffect, useMemo, useState } from "react";
import type { RunRecord } from "../api";
import { ApiError, api, type DiffResponse } from "../api";
import { DiffView, ErrorNote, StatusPill } from "../components";

/** Copy-ready commit message for the run's changes. */
export function commitMessage(run: RunRecord): string {
  const flows = run.flows.filter((f) => f.specFiles.length || f.planPath);
  const results = flows.flatMap((f) => f.results ?? []);
  const count = (s: string) => results.filter((r) => r.status === s).length;
  const subject = `test(dominion): add ${flows.map((f) => f.name.toLowerCase()).join(", ") || "generated"} tests`;
  const lines = [
    subject.length > 72 ? `${subject.slice(0, 69)}...` : subject,
    "",
    `Generated by DOMinion run ${run.id} (${run.env}/${run.role}, ${run.model}).`,
    ...flows.filter((f) => f.planPath).map((f) => `Plan: ${f.planPath}`),
    `Results: ${count("passed")} passed, ${count("failed") + count("timedOut")} failed, ${count("fixme")} fixme.`,
  ];
  const fixmes = results.filter((r) => r.status === "fixme");
  if (fixmes.length) {
    lines.push("", "Marked fixme (app behaviour looks broken):");
    for (const r of fixmes) lines.push(`- ${r.title.split(" > ").pop()}: ${r.fixmeReason ?? "see the comment in the test"}`);
  }
  return lines.join("\n");
}

export function Results({ run, live }: { run: RunRecord; live: boolean }) {
  const [diff, setDiff] = useState<DiffResponse>();
  const [error, setError] = useState<{ message: string; hint?: string }>();
  const [copied, setCopied] = useState(false);
  const results = useMemo(() => run.flows.flatMap((f) => (f.results ?? []).map((r) => ({ ...r, flow: f.name }))), [run]);
  const message = useMemo(() => commitMessage(run), [run]);
  const changedKey = run.changedFiles.map((c) => c.path).join("|") + (run.proposals ?? []).map((p) => p.status).join("|") + run.status;

  useEffect(() => {
    void api<DiffResponse>(`/api/runs/${run.id}/diff`).then(setDiff).catch((e: Error) => setError({ message: e.message }));
  }, [run.id, changedKey]);

  async function proposal(id: string, action: "apply" | "reject") {
    setError(undefined);
    try {
      await api(`/api/runs/${run.id}/proposals/${id}/${action}`, { method: "POST", json: {} });
      setDiff(await api<DiffResponse>(`/api/runs/${run.id}/diff`));
    } catch (e) {
      setError({ message: (e as Error).message, hint: (e as ApiError).hint });
    }
  }

  async function openTrace(path: string) {
    try {
      await api("/api/traces/open", { method: "POST", json: { path } });
    } catch (e) {
      setError({ message: (e as Error).message });
    }
  }

  return (
    <section className="card" aria-label="Results">
      <h2>Results</h2>
      {results.length ? (
        <table className="results">
          <thead>
            <tr>
              <th>Status</th>
              <th>Test</th>
              <th>Details</th>
            </tr>
          </thead>
          <tbody>
            {results.map((r) => (
              <tr key={`${r.file}:${r.title}`}>
                <td>
                  <StatusPill status={r.status} />
                </td>
                <td>
                  <div>{r.title.split(" > ").pop()}</div>
                  <div className="muted">{r.file}</div>
                </td>
                <td>
                  {r.status === "fixme" && r.fixmeReason ? <div className="tone-warn">fixme: {r.fixmeReason}</div> : null}
                  {r.error && r.status !== "passed" && r.status !== "fixme" ? <pre className="error-text">{r.error.split("\n").slice(0, 8).join("\n")}</pre> : null}
                  {r.healAttempts ? <div className="muted">healed {r.healAttempts}×</div> : null}
                  {r.tracePath ? (
                    <div className="row">
                      <a href={`/api/files?path=${encodeURIComponent(r.tracePath)}`} download>
                        Download trace
                      </a>
                      <button type="button" className="link" onClick={() => void openTrace(r.tracePath!)}>
                        Open in Trace Viewer
                      </button>
                    </div>
                  ) : null}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      ) : (
        <p className="muted">{live ? "Test results appear here after the first run." : "No tests were run."}</p>
      )}

      <h3>Changed files</h3>
      {diff?.files.length ? (
        diff.files.map((file) => (
          <details key={file.path} open={diff.files.length <= 3}>
            <summary>
              <span className={`kind kind-${file.kind}`}>{file.kind}</span> {file.path}
            </summary>
            <DiffView diff={file.diff} />
          </details>
        ))
      ) : (
        <p className="muted">No files changed.</p>
      )}

      {diff?.proposals.length ? (
        <>
          <h3>Proposed changes to hand-written files</h3>
          <p className="muted">DOMinion never edits your files directly. Apply a proposal only if it looks right.</p>
          {diff.proposals.map((p) => (
            <div key={p.id} className="proposal">
              <div className="row spread">
                <strong>{p.path}</strong>
                <StatusPill status={p.status === "pending" ? "awaiting_approval" : p.status === "applied" ? "done" : "rejected"} label={p.status} />
              </div>
              <DiffView diff={p.diff} />
              {p.status === "pending" ? (
                <div className="row">
                  <button type="button" className="primary" onClick={() => void proposal(p.id, "apply")}>
                    Apply
                  </button>
                  <button type="button" onClick={() => void proposal(p.id, "reject")}>
                    Reject
                  </button>
                </div>
              ) : null}
            </div>
          ))}
        </>
      ) : null}

      {run.changedFiles.length ? (
        <>
          <h3>Commit message</h3>
          <textarea aria-label="Commit message" readOnly rows={Math.min(12, message.split("\n").length + 1)} value={message} />
          <button
            type="button"
            onClick={() => {
              void navigator.clipboard?.writeText(message).then(() => setCopied(true));
            }}
          >
            {copied ? "Copied" : "Copy commit message"}
          </button>
        </>
      ) : null}
      <ErrorNote error={error?.message} hint={error?.hint} />
    </section>
  );
}
