import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import type { ProjectProfile } from "../config/schema";
import { renderTemplate } from "../templates";
import { projectRunsFile, readPlaywrightConfig } from "./scan";

/**
 * Non-DOMinion projects whose testDir contains DOMinion's testDir: they would also run the
 * generated tests, without DOMinion's baseURL and session (new projects only).
 */
export async function overlappingProjects(configPath: string, testDir: string): Promise<string[]> {
  const config = await readPlaywrightConfig(configPath);
  // A generated spec as DOMinion would write it: does the project's testDir, testMatch and
  // testIgnore let it run? (Setup projects with testMatch *.setup.ts and projects that already
  // ignore DOMinion's folder do not.)
  const sample = join(testDir, "area", "dominion-generated.spec.ts");
  return config.projects.filter((p) => !p.name.startsWith("dominion-") && projectRunsFile(p, sample)).map((p) => p.name);
}

export const DOMINION_PLAYWRIGHT_CONFIG = "playwright.dominion.config.ts";

/** Path of playwright.dominion.config.ts, next to the user's Playwright config. */
export function dominionPlaywrightConfigPath(root: string, profile: ProjectProfile): string {
  return join(dirname(resolve(root, profile.playwrightConfig)), DOMINION_PLAYWRIGHT_CONFIG);
}

/**
 * Writes playwright.dominion.config.ts, which imports the user's config and extends it with what
 * DOMinion needs (spec: Existing projects, Playwright config). The user's config is never patched.
 */
export function ensureDominionPlaywrightConfig(root: string, profile: ProjectProfile): { path: string; status: "created" | "updated" | "unchanged" | "foreign" } {
  const userConfig = resolve(root, profile.playwrightConfig);
  const path = dominionPlaywrightConfigPath(root, profile);
  const content = renderTemplate("playwright.dominion.config.ts.tmpl", {
    configFile: basename(userConfig),
    configImport: basename(userConfig).replace(/\.(ts|mts|cts|js|mjs|cjs)$/, ""),
  });
  if (existsSync(path)) {
    const current = readFileSync(path, "utf8");
    if (current === content) return { path, status: "unchanged" };
    if (!current.startsWith("// Generated by DOMinion")) return { path, status: "foreign" };
    writeFileSync(path, content, "utf8");
    return { path, status: "updated" };
  }
  writeFileSync(path, content, "utf8");
  return { path, status: "created" };
}
