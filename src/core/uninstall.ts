/** One change `dominion uninstall` makes. Nothing happens until `run` is called. */
export interface UninstallStep {
  action: "delete" | "edit";
  /** Repo-relative, with "/" at the end for folders. */
  path: string;
  /** What the change is, in a few words. */
  detail?: string;
  run(): void;
}

export interface UninstallPlan {
  root: string;
  steps: UninstallStep[];
  /** What is deliberately left in place, and why. */
  kept: string[];
  /** Things that could not be planned automatically. */
  warnings: string[];
  /** Whether package.json lists the DOMinion package. */
  packageInstalled: boolean;
}

export interface UninstallResult {
  done: UninstallStep[];
  failed: Array<{ step: UninstallStep; error: string }>;
}

const SOURCE_FILE = /\.(c|m)?(t|j)sx?$/;
const SESSION_FILE = /^[\w.-]+-[\w.-]+(\.headers)?\.json$/;

function walkFiles(dir: string): string[] {
  if (!existsSync(dir)) return [];
  const out: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === "node_modules" || entry.name === ".git") continue;
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walkFiles(path));
    else if (entry.isFile()) out.push(path);
  }
  return out;
}

/**
 * Removes empty folders under `dir`, and `dir` itself when it ends up empty. A folder holding only
 * the empty .gitkeep that init adds (so the folder can be committed) counts as empty.
 */
function pruneEmptyDirs(dir: string): void {
  if (!existsSync(dir) || !statSync(dir).isDirectory()) return;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) pruneEmptyDirs(join(dir, entry.name));
  }
  const left = readdirSync(dir);
  const onlyGitkeep = left.length === 1 && left[0] === ".gitkeep" && statSync(join(dir, ".gitkeep")).size === 0;
  if (left.length === 0 || onlyGitkeep) rmSync(dir, { recursive: true, force: true });
}

function startsWithDominionHeader(path: string): boolean {
  try {
    return readFileSync(path, "utf8").startsWith("// Generated by DOMinion");
  } catch {
    return false;
  }
}

/**
 * .env.local without what DOMinion put there: the template's comment lines, the API key, the role
 * credentials, and the empty placeholders it listed for an existing suite's variables. Values a
 * person filled in for the suite's own variables stay. Returns the names removed (never values).
 */
export function withoutDominionEnv(text: string, dominionNames: ReadonlySet<string>, placeholderNames: ReadonlySet<string>): { text: string; removed: string[] } {
  const eol = text.includes("\r\n") ? "\r\n" : "\n";
  const templateComments = new Set(
    renderTemplate("env.local.tmpl", { variables: "" })
      .split(/\r?\n/)
      .map((l) => l.trim())
      .filter((l) => l.startsWith("#")),
  );
  const removed: string[] = [];
  const kept = text.split(/\r?\n/).filter((line) => {
    if (templateComments.has(line.trim())) return false;
    const match = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$/.exec(line);
    if (!match) return true;
    const [, name, value] = match;
    const placeholder = placeholderNames.has(name!) && value!.trim().replace(/^(["'])\1$/, "") === "";
    if (dominionNames.has(name!) || placeholder) {
      removed.push(name!);
      return false;
    }
    return true;
  });
  // Drop blank lines left at the start and end.
  while (kept.length && kept[0]!.trim() === "") kept.shift();
  while (kept.length && kept[kept.length - 1]!.trim() === "") kept.pop();
  return { text: kept.length ? `${kept.join(eol)}${eol}` : "", removed };
}

/**
 * Works out everything `dominion uninstall` would remove from a project, without changing it.
 * Only DOMinion's own files and edits are listed: files it generated (they start with its header),
 * its config, folders and sessions, and the exact edits it made to the Playwright config.
 */
export async function planUninstall(root: string, options: { keepTests?: boolean } = {}): Promise<UninstallPlan> {
  const steps: UninstallStep[] = [];
  const kept: string[] = [];
  const warnings: string[] = [];
  const rel = (path: string) => relativePosix(root, path);
  const del = (path: string, detail?: string, folder = false) => {
    if (!isInside(root, path)) return;
    steps.push({ action: "delete", path: `${rel(path)}${folder ? "/" : ""}`, detail, run: () => rmSync(path, { recursive: true, force: true, maxRetries: 3, retryDelay: 200 }) });
  };

  let loaded: LoadedConfig | undefined;
  try {
    const candidate = await loadConfig({ cwd: root });
    if (resolve(candidate.root) === resolve(root)) loaded = candidate;
  } catch (error) {
    if (!(isDominionError(error) && error.code === "CONFIG_NOT_FOUND")) {
      warnings.push(`dominion.config could not be loaded (${errorMessage(error).split("\n")[0]}), so the default locations are used.`);
    }
  }
  const config = loaded?.config;
  const profile = config?.project;
  const ownTestDir = resolve(root, config?.testDir ?? DEFAULT_TEST_DIR);
  const generatedDir = profile ? resolve(root, profile.outputDir) : ownTestDir;
  const specsDir = resolve(root, config?.specsDir ?? "specs");

  // 1. The Playwright config(s): DOMinion's projects, import and testIgnore.
  const playwrightConfigs = new Set(findPlaywrightConfigs(root).map((name) => join(root, name)));
  if (profile) playwrightConfigs.add(resolve(root, profile.playwrightConfig));
  for (const path of playwrightConfigs) {
    if (!existsSync(path)) continue;
    const text = readFileSync(path, "utf8");
    const pattern = `**/${relativePosix(dirname(path), ownTestDir)}/**`;
    const { text: next, removed } = removeDominionFromPlaywrightConfig(text, pattern);
    if (!removed.length) continue;
    if (!parsesCleanly(next, path)) {
      warnings.push(`${rel(path)} could not be cleaned up automatically. Remove the lines between "// --- dominion:start" and "// --- dominion:end", and testIgnore: "${pattern}", by hand.`);
      continue;
    }
    steps.push({ action: "edit", path: rel(path), detail: `remove ${removed.join(", ")}`, run: () => writeFileSync(path, next, "utf8") });
  }

  // 2. playwright.dominion.config.ts (existing suites).
  const wrapper = profile ? dominionPlaywrightConfigPath(root, profile) : join(root, DOMINION_PLAYWRIGHT_CONFIG);
  if (existsSync(wrapper)) {
    if (startsWithDominionHeader(wrapper)) del(wrapper, "extends your Playwright config for DOMinion runs");
    else kept.push(`${rel(wrapper)}: it was not written by DOMinion.`);
  }

  // 3. The setup file that logs in before generated tests run.
  const setupFile = join(ownTestDir, SETUP_FILE_NAME);
  if (existsSync(setupFile) && startsWithDominionHeader(setupFile)) del(setupFile, "logs in before generated tests");

  // 4. Generated tests and page objects (they start with DOMinion's header), and plans.
  const generatedRoots = [generatedDir, ...(profile?.pageObjects ? [resolve(root, profile.pageObjects.dir)] : [])];
  const generated = [...new Set(generatedRoots.flatMap(walkFiles))].filter((file) => {
    if (file === setupFile || !SOURCE_FILE.test(file)) return false;
    try {
      return hasDominionHeader(readFileSync(file, "utf8"));
    } catch {
      return false;
    }
  });
  const plans = walkFiles(specsDir).filter((file) => {
    if (!file.endsWith(".md")) return false;
    try {
      const { frontmatter } = parsePlan(readFileSync(file, "utf8"));
      return Boolean(frontmatter.runId && frontmatter.flow && frontmatter.status);
    } catch {
      return false;
    }
  });
  if (options.keepTests) {
    if (generated.length) {
      kept.push(
        `${generated.length} generated test file${generated.length === 1 ? "" : "s"} in ${rel(generatedDir)}/ (--keep-tests). They expect DOMinion's saved login, so logged-in tests need your own login setup from now on.`,
      );
    }
    if (plans.length) kept.push(`${plans.length} test plan${plans.length === 1 ? "" : "s"} in ${rel(specsDir)}/ (--keep-tests).`);
  } else {
    for (const file of generated) del(file, "generated");
    for (const file of plans) del(file, "test plan");
  }

  // 5. DOMinion's own folders and config.
  const consumerDir = join(root, "dominion");
  if (existsSync(consumerDir)) {
    const count = walkFiles(consumerDir).length;
    del(consumerDir, `login script and prompt overrides, ${count} file${count === 1 ? "" : "s"}`, true);
  }
  const authDir = join(root, ".auth");
  if (existsSync(authDir)) {
    const files = readdirSync(authDir);
    const prefixes = config ? Object.entries(config.environments).flatMap(([env, e]) => Object.keys(e.roles).map((role) => `${env}-${role}.`)) : undefined;
    const ours = files.filter((name) => SESSION_FILE.test(name) && (!prefixes || prefixes.some((p) => name.startsWith(p))));
    if (ours.length === files.length && files.length) del(authDir, "saved logins", true);
    else {
      for (const name of ours) del(join(authDir, name), "saved login");
      if (files.length > ours.length) kept.push(`${files.length - ours.length} other file${files.length - ours.length === 1 ? "" : "s"} in .auth/: not DOMinion's saved logins.`);
    }
  }
  if (existsSync(join(root, ".dominion"))) del(join(root, ".dominion"), "run history and logs", true);
  const configFile = loaded?.configPath ?? DOMINION_CONFIG_NAMES.map((name) => join(root, name)).find((path) => existsSync(path));
  if (configFile) del(configFile);

  // 6. .env.local: DOMinion's variables only.
  const envPath = join(root, ENV_FILE);
  if (existsSync(envPath)) {
    const secretEnv = new Set(config?.secretEnv ?? []);
    const dominionNames = new Set(["ANTHROPIC_API_KEY", ...(config ? referencedEnvVars(config).map((r) => r.name) : [])].filter((name) => !secretEnv.has(name)));
    const original = readFileSync(envPath, "utf8");
    const { text, removed } = withoutDominionEnv(original, dominionNames, secretEnv);
    if (removed.length) {
      if (text === "") steps.push({ action: "delete", path: ENV_FILE, detail: `only held ${removed.join(", ")}`, run: () => rmSync(envPath, { force: true }) });
      else steps.push({ action: "edit", path: ENV_FILE, detail: `remove ${removed.join(", ")}`, run: () => writeFileSync(envPath, text, "utf8") });
    }
    if (text !== "") {
      const left = text.split(/\r?\n/).filter((l) => /^\s*(?:export\s+)?[A-Za-z_]\w*\s*=/.test(l)).length;
      if (left) kept.push(`${ENV_FILE}: ${left} variable${left === 1 ? "" : "s"} DOMinion did not add${secretEnv.size ? " (including your suite's own credentials)" : ""}.`);
    }
  }

  // 7. Empty folders left behind in DOMinion's own locations.
  const pruneRoots = [ownTestDir, ...(profile ? [generatedDir] : []), specsDir].filter((dir) => existsSync(dir));
  if (pruneRoots.length && steps.some((s) => s.action === "delete")) {
    steps.push({
      action: "delete",
      path: pruneRoots.map((dir) => `${rel(dir)}/`).join(", "),
      detail: "if empty afterwards",
      run: () => pruneRoots.forEach(pruneEmptyDirs),
    });
  }

  const gitignorePath = join(root, ".gitignore");
  if (existsSync(gitignorePath)) {
    const lines = readFileSync(gitignorePath, "utf8").split(/\r?\n/).map((l) => l.trim());
    if (REQUIRED_GITIGNORE_ENTRIES.some((entry) => lines.includes(entry))) kept.push(".gitignore entries for .env.local, .auth/ and .dominion/: harmless, and they keep secrets out of git.");
  }

  let packageInstalled = false;
  try {
    const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8")) as Record<string, Record<string, string> | undefined>;
    packageInstalled = Boolean(pkg.devDependencies?.[packageName()] ?? pkg.dependencies?.[packageName()]);
  } catch {
    // no package.json: nothing to uninstall
  }
  return { root, steps, kept, warnings, packageInstalled };
}

/** Applies the plan step by step; one failure does not stop the rest. */
export function applyUninstall(plan: UninstallPlan): UninstallResult {
  const result: UninstallResult = { done: [], failed: [] };
  for (const step of plan.steps) {
    try {
      step.run();
      result.done.push(step);
    } catch (error) {
      result.failed.push({ step, error: errorMessage(error).split("\n")[0]! });
    }
  }
  return result;
}

/** The package manager command that removes a package. */
export function removePackageCommand(pm: "npm" | "pnpm" | "yarn" | "bun", name: string): { command: string; args: string[] } {
  return pm === "npm" ? { command: "npm", args: ["uninstall", name] } : { command: pm, args: ["remove", name] };
}
