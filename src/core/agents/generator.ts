export const DEFAULT_TEST_IMPORT = 'import { test, expect } from "@playwright/test";';
const MAX_EXEMPLAR_LINES = 200;

/** Where and how a flow's tests are written (new project defaults, or the existing-project profile). */
export interface GenerationTarget {
  /** Absolute path of the spec file for the flow. */
  specPath: string;
  testImport: string;
  /** Absolute folder for page objects, when enabled. */
  pageObjectsDir?: string;
  /** Exact first line of every generated file. */
  header: string;
  describeTitle: string;
  /** Absolute folder the agent may read (the project's whole test folder). */
  readDir: string;
  /** Absolute folders the agent may write to. */
  writeDirs: string[];
  /** Existing project: hand-written files are protected (proposals instead of edits). */
  existingProject: boolean;
}

export function generationTarget(ctx: AgentContext, flow: FlowRun, planPath: string, flowName: string): GenerationTarget {
  const profile = ctx.loaded.config.project;
  const root = ctx.paths.root;
  const header = `// Generated by DOMinion from ${relativePosix(root, planPath)} (run ${ctx.run.id})`;
  const describeTitle = `${flowName} @dominion @flow:${flow.id} @role:${ctx.roleName}`;
  if (profile) {
    const outputDir = resolve(root, profile.outputDir);
    const pageObjectsDir = profile.pageObjects ? resolve(root, profile.pageObjects.dir) : undefined;
    return {
      specPath: join(outputDir, profile.fileNaming.replace("{flow}", flow.id)),
      testImport: profile.testImport,
      pageObjectsDir,
      header,
      describeTitle,
      readDir: resolve(root, profile.testDir),
      writeDirs: [outputDir, ...(pageObjectsDir ? [pageObjectsDir] : [])],
      existingProject: true,
    };
  }
  const area = flow.area ?? "flows";
  return {
    specPath: join(ctx.paths.testDir, area, `${flow.id}.spec.ts`),
    testImport: DEFAULT_TEST_IMPORT,
    pageObjectsDir: ctx.loaded.config.pageObjects ? join(ctx.paths.testDir, "pages") : undefined,
    header,
    describeTitle,
    readDir: ctx.paths.testDir,
    writeDirs: [ctx.paths.testDir],
    existingProject: false,
  };
}

/** Content check run before every write (lint + ownership), returning blocking problems. */
export function generatorContentCheck(ctx: AgentContext, flow: FlowRun, target: GenerationTarget) {
  return (absPath: string, content: string): string | undefined => {
    const rel = relativePosix(ctx.paths.root, absPath);
    const name = basename(absPath).toLowerCase();
    if (name === SETUP_FILE_NAME || name.startsWith("playwright.dominion.config")) return `${rel} is managed by DOMinion and cannot be edited.`;
    if (existsSync(absPath) && !hasDominionHeader(readFileSync(absPath, "utf8")) && !(target.existingProject && ctx.loaded.config.project?.modifyExisting)) {
      return `${rel} was written by a person (it has no DOMinion header). DOMinion never modifies hand-written files; create a new file instead.`;
    }
    const isPageObject = target.pageObjectsDir !== undefined && isInside(target.pageObjectsDir, absPath);
    const isSpec = /\.(spec|test)\.(ts|js|mjs|cjs)$/.test(absPath);
    const issues = lintGeneratedFile(content, {
      kind: isPageObject ? "page-object" : isSpec ? "spec" : "support",
      flowSlug: isSpec ? flow.id : undefined,
      role: isSpec ? ctx.roleName : undefined,
      testImport: isSpec ? target.testImport : undefined,
      redactor: ctx.redactor,
      baseURL: ctx.env.baseURL,
    });
    if (!isSpec && !hasDominionHeader(content)) {
      issues.unshift({ rule: "header-comment", severity: "error", line: 1, message: `Start the file with the header comment: ${target.header}` });
    }
    const errors = lintErrors(issues);
    return errors.length ? formatLintIssues(rel, errors) : undefined;
  };
}

function pageObjectLines(root: string, pageObjects: readonly PageObjectInfo[]): string[] {
  return pageObjects.map((po) => {
    const locators = po.locators.length ? `; locators: ${po.locators.map((l) => `${l.name} = ${l.locator.slice(0, 90)}`).join("; ")}` : "";
    return `- ${po.className} (${po.file}): methods ${po.methods.join(", ") || "none"}${locators}`;
  });
}

function exemplarBlock(root: string, file: string): string {
  const abs = join(root, file);
  if (!existsSync(abs)) return "";
  const lines = readFileSync(abs, "utf8").split(/\r?\n/);
  const body = lines.slice(0, MAX_EXEMPLAR_LINES).join("\n") + (lines.length > MAX_EXEMPLAR_LINES ? "\n// ... (truncated)" : "");
  return [`${file}:`, "```ts", body, "```"].join("\n");
}

export function buildGeneratorPrompt(ctx: AgentContext, flow: FlowRun, planPath: string, target: GenerationTarget, scan?: SourceScan): string {
  const root = ctx.paths.root;
  const plan = readPlan(planPath);
  const rel = (p: string) => relativePosix(root, p);
  const source = scan ?? scanSources(root, target.readDir);
  const profile = ctx.loaded.config.project;
  const otherSpecs = source.testFiles.map((t) => t.file).filter((f) => f !== rel(target.specPath));
  const lines = [
    `Generate Playwright tests for the approved plan ${rel(planPath)}.`,
    "",
    `Environment: ${ctx.env.name} (base URL ${ctx.env.baseURL}); role: ${roleDescription(ctx)}.`,
    `Irreversible actions: ${destructiveRule(ctx.env)}`,
    "",
    `Write the spec to exactly: ${rel(target.specPath)}`,
    `First line of the file (exactly): ${target.header}`,
    `Import (exactly): ${target.testImport}`,
    `Describe title (exactly): "${target.describeTitle}"`,
    "One test per scenario, titled with the scenario's title in lower-case sentence form; one test.step per plan step using the step's wording.",
  ];
  if (target.existingProject && profile) {
    lines.push(
      "",
      "This project already has a Playwright suite with its own conventions. The new tests must look like a teammate wrote them: follow the exemplars below for structure, naming, fixtures, page object use and assertion style, and use the project's fixtures from the import above.",
    );
    if (profile.conventions) lines.push("", "Conventions summary:", profile.conventions.trim());
    const fixtures = source.fixtures.flatMap((f) => f.fixtures.map((name) => `${name} (${f.file})`));
    if (fixtures.length) lines.push("", `Fixtures available through the import: ${fixtures.join(", ")}.`);
    if (profile.exemplars.length) {
      lines.push("", "Style exemplars (existing tests from this project):");
      for (const file of profile.exemplars) {
        const block = exemplarBlock(root, file);
        if (block) lines.push(block);
      }
    }
    lines.push(
      "",
      profile.modifyExisting
        ? "You may extend existing page objects when a step needs it."
        : "Do not change existing page objects, fixtures or helpers. If you try, the change is saved as a proposal for a person to review and is NOT applied, so write tests that work with the code as it is.",
    );
  } else {
    lines.push("", "Seed test (how every test starts):", "```ts", seedTest(ctx, target.testImport), "```");
  }
  if (target.pageObjectsDir) {
    lines.push(
      "",
      `Page objects folder: ${rel(target.pageObjectsDir)}. Create a new page object only for a page used by two or more flows (other specs are listed below), and start the file with the header line. Call an existing page object method whenever one covers a step instead of writing a duplicate.`,
    );
    lines.push(source.pageObjects.length ? "Existing page objects:" : "There are no page objects yet.", ...pageObjectLines(root, source.pageObjects));
  }
  lines.push("", otherSpecs.length ? `Other specs in the test folder: ${otherSpecs.slice(0, 40).join(", ")}` : "There are no other specs in the test folder yet.");
  lines.push("", "The approved plan:", "```markdown", plan.body.trim(), "```");
  return lines.join("\n");
}

export interface GeneratorOutput {
  result: AgentResult;
  target: GenerationTarget;
}

/** Runs the generator agent; the caller diffs the test folder to see what it wrote. */
export async function runGenerator(ctx: AgentContext, flow: FlowRun, planPath: string, flowName: string): Promise<GeneratorOutput> {
  if (!existsSync(planPath)) {
    throw new DominionError(`Plan not found: ${relativePosix(ctx.paths.root, planPath)}`, { code: "PLAN_NOT_FOUND" });
  }
  const target = generationTarget(ctx, flow, planPath, flowName);
  const modifyExisting = ctx.loaded.config.project?.modifyExisting ?? false;
  const result = await ctx.runner.run(
    {
      agent: "generator",
      flowId: flow.id,
      model: ctx.model,
      systemPrompt: renderPrompt("generator", { testIdAttribute: ctx.loaded.config.testIdAttribute }, ctx.paths.promptOverridesDir, ctx.paths.root),
      prompt: buildGeneratorPrompt(ctx, flow, planPath, target),
      maxTurns: ctx.loaded.config.budgets.maxTurnsPerAgent,
      maxBudgetUsd: ctx.remainingBudget(),
      cwd: ctx.paths.root,
      mcp: mcpForRun(ctx),
      screenshotDir: ctx.run.path("screenshots"),
      hiddenEnvVars: credentialEnvVars(ctx),
      signal: ctx.signal,
      policy: {
        agent: "generator",
        root: ctx.paths.root,
        builtinTools: ["Read", "Write", "Edit", "Glob", "Grep"],
        mcpTools: [...BROWSER_READ_TOOLS, ...BROWSER_INPUT_TOOLS, ...BROWSER_VERIFY_TOOLS],
        readRoots: [target.readDir],
        writeRoots: target.writeDirs,
        writeExtensions: [".ts", ".js", ".mjs", ".cjs"],
        checkContent: generatorContentCheck(ctx, flow, target),
        env: ctx.env,
        excludePatterns: ctx.loaded.config.crawl.exclude,
        redactor: ctx.redactor,
        ...(target.existingProject && !modifyExisting && ctx.onProposal
          ? {
              proposals: {
                isProtected: (abs: string) => !hasDominionHeader(readFileSync(abs, "utf8")),
                record: (abs: string, before: string, after: string) => ctx.onProposal!(abs, before, after, flow.id),
              },
            }
          : {}),
      },
    },
    (payload) => ctx.run.emit(payload),
  );
  return { result, target };
}

/** Run ID and plan path from a generated file's header comment. */
export function parseHeader(content: string): { plan: string; runId: string } | undefined {
  const first = content.split(/\r?\n/).find((l) => l.trim());
  const match = first ? HEADER_RE.exec(first.trim()) : null;
  return match ? { plan: match[1]!, runId: match[2]! } : undefined;
}
